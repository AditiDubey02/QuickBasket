class Product {
  final int id;
  final String name;
  final String description;
  final String image;
  final double price;
  final String quantity;
  final String category;

  Product({
    required this.id,
    required this.name,
    required this.description,
    required this.image,
    required this.price,
    required this.quantity,
    required this.category,
  });
}
